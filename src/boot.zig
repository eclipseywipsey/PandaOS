//! Bootloader stage: GRUB, with a hand-written grub.cfg.
//!
//! We do not use grub-mkconfig: it probes the root filesystem with
//! grub-probe, which handles FFS poorly. PandaOS boots from a known layout,
//! so a small static config is more predictable.
//! x86_64 only for now.

const std = @import("std");
const cfg = @import("config.zig");
const layout = @import("layout.zig");
const disk = @import("disk.zig");
const exec = @import("exec.zig");
const target = @import("target.zig");

/// Kernel names on /boot: vmlinuz-<kernel> and initramfs-<kernel>.img.
pub fn grubCfg(a: std.mem.Allocator, kernel: []const u8, root_dev: []const u8, root_fs: layout.Fs, has_initramfs: bool) ![]u8 {
    const rootflags: []const u8 = switch (root_fs) {
        .ffs => " rootfstype=ufs rootflags=ufstype=44bsd",
        .btrfs => " rootfstype=btrfs",
        else => "",
    };
    const initrd = if (has_initramfs)
        try std.fmt.allocPrint(a, "    initrd /initramfs-{s}.img\n", .{kernel})
    else
        try a.dupe(u8, "");

    return std.fmt.allocPrint(a,
        \\# PandaOS: generated by pandaos-install
        \\set default=0
        \\set timeout=3
        \\
        \\insmod part_gpt
        \\insmod part_msdos
        \\insmod ufs1
        \\insmod btrfs
        \\
        \\menuentry "PandaOS ({s})" {{
        \\    search --no-floppy --file --set=root /vmlinuz-{s}
        \\    linux /vmlinuz-{s} root={s}{s} rw quiet
        \\{s}}}
        \\
    , .{ kernel, kernel, kernel, root_dev, rootflags, initrd });
}

fn bindMounts(a: std.mem.Allocator, root: []const u8) !void {
    const pairs = [_][2][]const u8{
        .{ "/dev", "dev" },
        .{ "/proc", "proc" },
        .{ "/sys", "sys" },
    };
    for (pairs) |p| {
        const dest = try std.fmt.allocPrint(a, "{s}/{s}", .{ root, p[1] });
        if (!exec.dry_run) try std.fs.cwd().makePath(dest);
        try exec.run(a, &.{ "mount", "--bind", p[0], dest });
    }
}

pub fn install(a: std.mem.Allocator, root: []const u8, c: cfg.Config) !void {
    var root_slice: ?layout.Slice = null;
    for (c.slices) |s| if (std.mem.eql(u8, s.mount, "/")) {
        root_slice = s;
    };
    const rs = root_slice orelse return error.NoRootSlice;
    const root_dev = try disk.partPath(a, c.disk, rs.index);

    const kernel = c.kernel.name();
    const initramfs_path = try std.fmt.allocPrint(a, "boot/initramfs-{s}.img", .{kernel});
    const has_initramfs = blk: {
        if (exec.dry_run) break :blk false;
        const full = try std.fs.path.join(a, &.{ root, initramfs_path });
        std.fs.cwd().access(full, .{}) catch break :blk false;
        break :blk true;
    };

    const text = try grubCfg(a, kernel, root_dev, rs.fs, has_initramfs);
    try target.writeFile(a, root, "boot/grub/grub.cfg", text, 0o644);

    try bindMounts(a, root);

    const modules = "--modules=ufs1 ufs2 btrfs part_gpt part_msdos";
    if (c.uefi and c.partition != .mbr) {
        try exec.runIn(a, root, &.{
            "grub-install",  "--target=x86_64-efi", "--efi-directory=/boot/efi",
            "--boot-directory=/boot", "--removable", modules,
        });
    } else {
        try exec.runIn(a, root, &.{
            "grub-install", "--target=i386-pc", "--boot-directory=/boot", modules, c.disk,
        });
    }
}

test "grub.cfg has FFS root flags and the initramfs line when present" {
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const t = try grubCfg(a, "linux-libre", "/dev/sda3", .ffs, true);
    try std.testing.expect(std.mem.indexOf(u8, t, "root=/dev/sda3 rootfstype=ufs rootflags=ufstype=44bsd") != null);
    try std.testing.expect(std.mem.indexOf(u8, t, "initrd /initramfs-linux-libre.img") != null);
    const t2 = try grubCfg(a, "linux", "/dev/sda3", .ffs, false);
    try std.testing.expect(std.mem.indexOf(u8, t2, "initrd") == null);
}
